"use client"

import { useState } from 'react'
import { FileText, Copy, Check, ExternalLink } from 'lucide-react'

const EXAMPLE_REPORTS = [
  {
    id: 'rpt_a1b2c3',
    title: 'Agent loop audit',
    created: '2026-06-14',
    bottlenecks: 6,
    improvement: '82 ms',
    findings: [
      { rank: 1, severity: 'high', title: 'Sequential tool calls', lost: '48ms' },
      { rank: 2, severity: 'medium', title: 'Sync output streaming', lost: '22ms' },
      { rank: 3, severity: 'low', title: 'Cold start on each request', lost: '12ms' },
    ],
  },
  {
    id: 'rpt_d4e5f6',
    title: 'RAG retrieval path',
    created: '2026-06-13',
    bottlenecks: 4,
    improvement: '64 ms',
    findings: [
      { rank: 1, severity: 'high', title: 'Blocking I/O in retrieval', lost: '40ms' },
      { rank: 2, severity: 'medium', title: 'No cache on repeated queries', lost: '24ms' },
    ],
  },
]

const SEVERITY_COLOR: Record<string, string> = {
  high: 'text-red-400 border-red-400/20 bg-red-400/5',
  medium: 'text-yellow-400 border-yellow-400/20 bg-yellow-400/5',
  low: 'text-green-400 border-green-400/20 bg-green-400/5',
}

export default function ReportsPage() {
  const [selected, setSelected] = useState(EXAMPLE_REPORTS[0])
  const [copied, setCopied] = useState(false)

  function copyLink() {
    navigator.clipboard.writeText(`https://arclat.vercel.app/share?id=${selected.id}`)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  return (
    <main className="mx-auto flex w-full max-w-6xl flex-1 flex-col gap-8 px-6 py-10 sm:px-10 lg:px-12">

      <div className="flex flex-col gap-1">
        <p className="text-[10px] uppercase tracking-widest text-[var(--muted)]">Reports</p>
        <h1 className="text-3xl font-semibold text-[var(--text)]">Shared audit reports</h1>
        <p className="mt-1 text-sm text-[var(--muted)]">
          Reports generated by <code className="rounded bg-white/5 px-1 py-0.5 text-xs">audit_codebase</code> in Claude Code.
          Share them with your team via link.
        </p>
      </div>

      <div className="grid gap-6 lg:grid-cols-[280px_1fr]">

        {/* Sidebar - report list */}
        <aside className="flex flex-col gap-2">
          {EXAMPLE_REPORTS.map((r) => (
            <button
              key={r.id}
              onClick={() => setSelected(r)}
              className={`flex flex-col gap-1.5 rounded-xl border p-4 text-left transition-colors ${
                selected.id === r.id
                  ? 'border-[var(--accent)]/40 bg-[var(--accent)]/5'
                  : 'border-white/10 hover:bg-white/5'
              }`}
            >
              <div className="flex items-center gap-2">
                <FileText size={13} className="text-[var(--accent)]" />
                <span className="text-sm font-medium text-[var(--text)]">{r.title}</span>
              </div>
              <p className="text-xs text-[var(--muted)]">{r.bottlenecks} bottlenecks · ~{r.improvement} saved</p>
              <p className="text-[10px] text-[var(--muted)]">{r.created}</p>
            </button>
          ))}

          <div className="mt-2 rounded-xl border border-white/10 bg-white/5 p-4">
            <p className="text-xs text-[var(--muted)]">
              Run <code className="rounded bg-white/5 px-1 text-[11px]">audit_codebase</code> from Claude Code to generate real reports.
            </p>
          </div>
        </aside>

        {/* Main - report detail */}
        <section className="flex flex-col gap-4">
          <div className="rounded-xl border border-white/10 bg-[var(--card)] p-6">
            <div className="flex items-start justify-between gap-4">
              <div>
                <h2 className="text-xl font-semibold text-[var(--text)]">{selected.title}</h2>
                <p className="mt-1 text-sm text-[var(--muted)]">
                  {selected.bottlenecks} bottlenecks found · ~{selected.improvement} estimated improvement
                </p>
              </div>
              <div className="flex gap-2">
                <button
                  onClick={copyLink}
                  className="flex items-center gap-1.5 rounded-lg border border-white/10 px-3 py-1.5 text-xs text-[var(--muted)] hover:bg-white/5 hover:text-[var(--text)]"
                >
                  {copied ? <Check size={12} className="text-[var(--accent)]" /> : <Copy size={12} />}
                  {copied ? 'Copied' : 'Copy link'}
                </button>
                <a
                  href={`/share?id=${selected.id}`}
                  className="flex items-center gap-1.5 rounded-lg border border-white/10 px-3 py-1.5 text-xs text-[var(--muted)] hover:bg-white/5 hover:text-[var(--text)]"
                >
                  <ExternalLink size={12} />
                  Open
                </a>
              </div>
            </div>

            <div className="mt-6 flex flex-col gap-3">
              {selected.findings.map((f) => (
                <div key={f.rank} className="flex items-center gap-4 rounded-lg border border-white/10 p-4">
                  <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full border border-white/10 text-xs font-semibold text-[var(--muted)]">
                    {f.rank}
                  </span>
                  <div className="flex-1">
                    <p className="text-sm font-medium text-[var(--text)]">{f.title}</p>
                  </div>
                  <span className={`rounded-full border px-2.5 py-0.5 text-[10px] font-medium uppercase tracking-wider ${SEVERITY_COLOR[f.severity]}`}>
                    {f.severity}
                  </span>
                  <span className="text-sm font-semibold text-[var(--accent)]">~{f.lost}</span>
                </div>
              ))}
            </div>
          </div>

          <div className="rounded-xl border border-white/10 bg-white/5 p-5">
            <p className="text-xs uppercase tracking-widest text-[var(--muted)]">Report ID</p>
            <p className="mt-1 font-mono text-sm text-[var(--text)]">{selected.id}</p>
            <p className="mt-3 text-xs text-[var(--muted)]">
              These are example reports. Connect Claude Code with the Arclat MCP server to generate real ones from your codebase.
            </p>
          </div>
        </section>
      </div>
    </main>
  )
}
